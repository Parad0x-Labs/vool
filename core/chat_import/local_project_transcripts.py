"""Reader for a terminal coding assistant's per-project transcripts (the Claude Code layout).

Format (sources kept in the mission's FORMATS.md: the tool's official docs for locations, and the
vendor's own open-source agent SDK parser, anthropics/claude-agent-sdk-python at e1464e58, for the
line fields; the docs call the line format internal, so anything unrecognised is reported and
never guessed at):

* the tool's folder is ``$CLAUDE_CONFIG_DIR`` when set, else ``~/.claude``;
* each session is ``projects/<project>/<session id>.jsonl``, where ``<project>`` is the working
  folder with every non-alphanumeric character replaced by ``-``. Helper transcripts live in
  sub-folders of a session and set-aside copies carry ``.orphaned-``/``.superseded-`` in their
  names; neither is a chat the person had;
* lines with ``type`` ``user``/``assistant``/``progress``/``system``/``attachment`` carry ``uuid``
  and ``parentUuid`` and form a tree; the conversation shown is the path from the newest main
  leaf back to the root. Lines marked ``isMeta``, ``isSidechain`` or with a ``teamName`` are not
  the person's conversation. ``isCompactSummary`` lines hold the summary that replaced older
  turns. ``custom-title``/``ai-title`` lines name the session;
* ``message`` is a model API message: ``role`` and ``content`` (a string, or blocks such as
  ``text``, ``tool_use`` with ``input``, ``tool_result``, ``thinking``). Each line also carries
  ``cwd``, ``gitBranch`` and ``timestamp``.

Only user and assistant text becomes messages. The latest summary and the latest to-do list
are kept as separately reviewed context, with the working folder, branch and models. Nothing
here writes to the tool's folder.
"""
from __future__ import annotations

import contextlib
import json
import re
from pathlib import Path
from typing import Any

from core.chat_import.common import Limits, as_text, bump, iso_seconds, make_message, read_regular_file
from core.chat_import.model import ImportedChat, ImportedMessage, ReadResult

FORMAT = "claude_code_jsonl"

_CHAIN_TYPES = frozenset({"user", "assistant", "progress", "system", "attachment"})
_NAME = re.compile(r"[0-9A-Za-z][0-9A-Za-z_-]*\.jsonl")
#: Text the tool writes into user turns that the person did not type (command echoes, hook and
#: reminder blocks, interruption marks).
_INJECTED_PREFIXES = (
    "<local-command-stdout>", "<local-command-stderr>", "<command-name>", "<command-message>",
    "<command-args>", "<session-start-hook>", "<system-reminder>", "<tick>", "<goal>",
    "<ide_opened_file>", "<ide_selection>",
    "[request interrupted by user", "caveat: the messages below were generated by the user while running local commands",
)
_MAX_LINE_BYTES = 16 << 20
_TODO_TOOL = "TodoWrite"


def state_dir(home: Path, env: dict[str, str]) -> Path | None:
    configured = str(env.get("CLAUDE_CONFIG_DIR") or "").strip()
    root = Path(configured).expanduser() if configured else home / ".claude"
    return root if root.is_dir() and not root.is_symlink() else None


def store_paths(home: Path, env: dict[str, str]) -> list[Path]:
    """Session transcripts that exist. Directory listings only."""
    root = state_dir(home, env)
    if root is None:
        return []
    found: list[Path] = []
    with contextlib.suppress(OSError):
        projects = root / "projects"
        if projects.is_dir() and not projects.is_symlink():
            for project in sorted(projects.iterdir()):
                if not project.is_dir() or project.is_symlink():
                    continue
                with contextlib.suppress(OSError):
                    found.extend(sorted(path for path in project.iterdir() if _NAME.fullmatch(path.name)))
    return found


def read_stores(paths: list[Path], limits: Limits) -> ReadResult:
    chats: list[ImportedChat] = []
    problems: list[str] = []
    truncated = False
    budget = limits.max_local_store_bytes
    for count, path in enumerate(paths):
        if count >= limits.max_local_files or len(chats) >= limits.max_conversations:
            problems.append("too_many_chats")
            truncated = True
            break
        try:
            raw = read_regular_file(path, budget)
        except ValueError:
            problems.append("store_too_large")
            break
        except OSError:
            problems.append("files_skipped")
            continue
        budget -= len(raw)
        records = _lines(raw, problems)
        if records is None:
            continue
        chat, cut = _chat_from_records(records, path.stem, limits, problems)
        if chat is None:
            continue
        truncated = truncated or cut
        root = path.parents[2]
        chats.append(ImportedChat(
            source_format=chat.source_format, source_chat_id=chat.source_chat_id, title=chat.title,
            created_at=chat.created_at, updated_at=chat.updated_at, messages=chat.messages, skipped=chat.skipped,
            context={**chat.context, "profile_root": str(root),
                     "project_memory": f"projects/{path.parent.name}/memory"}))
    source_format = FORMAT if chats or not problems else ""
    return ReadResult(source_format=source_format, chats=tuple(chats), problems=tuple(dict.fromkeys(problems)),
                      truncated=truncated)


def _lines(raw: bytes, problems: list[str]) -> list[dict] | None:
    records: list[dict] = []
    pieces = raw.split(b"\n")
    for index, line in enumerate(pieces):
        if not line.strip():
            continue
        record = None
        if len(line) <= _MAX_LINE_BYTES:
            with contextlib.suppress(ValueError, RecursionError, UnicodeDecodeError):
                record = json.loads(line)
        if not isinstance(record, dict):
            if index == len(pieces) - 1:
                continue  # the line the tool was still writing
            problems.append("rows_unreadable_skipped")
            return None
        records.append(record)
    if not records:
        problems.append("files_skipped")
        return None
    return records


def is_injected(text: str) -> bool:
    return text.strip().lower().startswith(_INJECTED_PREFIXES)


def _content(message: dict, role: str) -> tuple[str | None, str, list[dict]]:
    """(text, reason when there is none, tool calls)."""
    content = message.get("content")
    if isinstance(content, str):
        if role == "user" and is_injected(content):
            return None, "context", []
        return (content, "", []) if content.strip() else (None, "empty", [])
    if not isinstance(content, list):
        return None, "empty", []
    texts: list[str] = []
    calls: list[dict] = []
    reasons: set[str] = set()
    for block in content:
        kind = block.get("type") if isinstance(block, dict) else None
        if kind == "text" and isinstance(block.get("text"), str):
            if role == "user" and is_injected(block["text"]):
                reasons.add("context")
            elif block["text"].strip():
                texts.append(block["text"])
        elif kind == "tool_use":
            calls.append(block)
            reasons.add("tool")
        elif kind == "tool_result":
            reasons.add("tool")
        elif kind in ("thinking", "redacted_thinking"):
            reasons.add("thinking")
        else:
            reasons.add("non_text")
    if texts:
        return "\n\n".join(texts), "", calls
    for reason in ("tool", "context", "thinking", "non_text"):
        if reason in reasons:
            return None, reason, calls
    return None, "empty", calls


def _todo_text(call: dict) -> str:
    todos = (call.get("input") or {}).get("todos") if isinstance(call.get("input"), dict) else None
    if not isinstance(todos, list):
        return ""
    return "\n".join(f"[{as_text(item.get('status')) or 'pending'}] {as_text(item.get('content')).strip()}"
                     for item in todos[:100] if isinstance(item, dict) and as_text(item.get("content")).strip())


def _path(records: list[dict]) -> tuple[list[dict], int]:
    """The shown conversation (root first) and how many chain entries are on other branches."""
    chain = [(index, record) for index, record in enumerate(records)
             if record.get("type") in _CHAIN_TYPES and isinstance(record.get("uuid"), str)]
    by_id = {record["uuid"]: (index, record) for index, record in chain}
    parents = {record.get("parentUuid") for _index, record in chain}

    def main(record: dict) -> bool:
        return not record.get("isSidechain") and not record.get("teamName") and not record.get("isMeta")

    leaves = []
    for _index, record in chain:
        if record["uuid"] in parents:
            continue
        node: Any = record
        seen: set[str] = set()
        # Walk back from each end to the nearest turn of the main conversation, past helper,
        # meta and bookkeeping entries hung under it.
        while isinstance(node, dict) and (node.get("type") not in ("user", "assistant") or not main(node)) \
                and node["uuid"] not in seen:
            seen.add(node["uuid"])
            node = by_id.get(node.get("parentUuid"), (0, None))[1]
        if isinstance(node, dict) and node.get("type") in ("user", "assistant") and main(node):
            leaves.append((by_id[record["uuid"]][0], node))
    if not leaves:
        return [], 0
    leaf = max(leaves, key=lambda item: item[0])[1]
    path: list[dict] = []
    seen = set()
    node = leaf
    while isinstance(node, dict) and node["uuid"] not in seen:
        seen.add(node["uuid"])
        path.append(node)
        node = by_id.get(node.get("parentUuid"), (0, None))[1]
    path.reverse()
    visible = sum(1 for record in path if record.get("type") in ("user", "assistant") and main(record))
    total = sum(1 for _index, record in chain if record.get("type") in ("user", "assistant") and main(record))
    return path, max(0, total - visible)


def _chat_from_records(records: list[dict], session: str, limits: Limits,
                       problems: list[str]) -> tuple[ImportedChat | None, bool]:
    from core.chat_import.source_context import tool_paths

    first = next((record for record in records if record.get("type") in _CHAIN_TYPES), None)
    if first is not None and first.get("isSidechain"):
        problems.append("chats_internal_skipped")
        return None, False
    path, hidden = _path(records)
    if not path:
        problems.append("store_version_unknown" if any(isinstance(r.get("type"), str) for r in records) else "files_skipped")
        return None, False
    skipped: dict[str, int] = {}
    if hidden:
        skipped["hidden_branch"] = hidden
    title = ai_title = ""
    for record in records:
        if record.get("type") == "custom-title" and as_text(record.get("customTitle")).strip():
            title = record["customTitle"]
        elif record.get("type") == "ai-title" and as_text(record.get("aiTitle")).strip():
            ai_title = record["aiTitle"]
    messages: list[ImportedMessage] = []
    summary = plan = cwd = branch = ""
    models: list[str] = []
    references: list[str] = []
    truncated = False
    last_time: float | None = None
    for record in path:
        kind = record.get("type")
        cwd = as_text(record.get("cwd")) or cwd
        branch = as_text(record.get("gitBranch")) or branch
        if kind not in ("user", "assistant"):
            continue
        message = record.get("message")
        if not isinstance(message, dict):
            bump(skipped, "malformed")
            continue
        if record.get("isMeta") or record.get("isSidechain") or record.get("teamName"):
            bump(skipped, "context")
            continue
        text, reason, calls = _content(message, kind)
        for call in calls:
            if call.get("name") == _TODO_TOOL:
                plan = _todo_text(call) or plan
            else:
                references.extend(tool_paths([{"input": call.get("input")}]))
        if record.get("isCompactSummary"):
            summary = text or summary
            bump(skipped, "context")
            continue
        model = as_text(message.get("model")).strip()
        if kind == "assistant" and model and not model.startswith("<"):
            models = [m for m in models if m != model] + [model]
        if text is None:
            bump(skipped, reason)
            continue
        if len(messages) >= limits.max_messages_per_chat:
            bump(skipped, "limit")
            continue
        when = iso_seconds(record.get("timestamp"))
        imported, cut = make_message(kind, text, when, limits)
        truncated = truncated or cut
        messages.append(imported)
        if when is not None:
            last_time = when if last_time is None else max(last_time, when)
    notes = []
    if summary:
        notes.append({"text": summary, "source": "conversation_summary", "scope": "chat"})
    if plan:
        notes.append({"text": plan, "source": "plan", "scope": "chat"})
    created_at = iso_seconds(path[0].get("timestamp")) or (messages[0].created_at if messages else None)
    return (
        ImportedChat(
            source_format=FORMAT,
            source_chat_id=as_text(path[0].get("sessionId") or session)[:200],
            title=as_text(title or ai_title),
            created_at=created_at,
            updated_at=last_time or created_at,
            messages=tuple(messages),
            skipped=skipped,
            context={"workspace_hint": cwd, "models": models[-5:], "notes": notes, "file_references": references[:100],
                     **({"branch": branch[:200]} if branch else {})},
        ),
        truncated,
    )
