@dataclass(frozen=True)
class ToolClaim:
    """How to check that an answer only claims what this tool actually produced.

    A tool declares where its target and its results live in its own observation, so the binder
    needs no per-tool regex and a third-party tool is covered the moment it is registered. Without
    this the check has to guess at each tool's output shape, which is the thing that does not
    generalise past the tools someone remembered to hand-code.

    ``target_argument``    the argument naming what the tool acts on ("path", "jql")
    ``resolved_target_key`` where the tool reports what it ACTUALLY resolved that to — which is
                            not the same string when a user types "~/Desktop/x"
    ``result_items_key``   where the list of returned item names lives, for checking that an
                            answer does not invent a filename
    ``cites``              observation values an answer must quote at least one of
    ``asserts_action``     whether a receipt from this tool can back a claim that something changed
    """

    target_argument: str = ""
    resolved_target_key: str = ""
    result_items_key: str = ""
    cites: tuple[str, ...] = ()
    asserts_action: bool = False

    @property
    def is_declared(self) -> bool:
        return bool(self.target_argument or self.resolved_target_key or self.result_items_key)


@dataclass(frozen=True)
class RuntimeToolContract:
    intent: str
    description: str
    tool_surface: str
    capability_id: str
    capability_claim: str
    supported: bool
    unsupported_reason: str
    input_schema: dict[str, str]
    output_schema: dict[str, str]
    side_effect_class: str
    approval_requirement: str
    timeout_policy: str
    retry_policy: str
    artifact_emission: str
    error_contract: str

    # Appended with defaults so the 52 existing keyword-constructed literals below compile
    # untouched. Each replaces something currently derived by matching on the intent STRING in a
    # different module — the derivation that a third-party tool can never participate in.
    handler: str = "runtime"
    json_schema: dict[str, Any] = field(default_factory=dict)
    claim: ToolClaim = field(default_factory=ToolClaim)
    permission_actions: tuple[str, ...] = ()
    source: str = "builtin"
    # The Blackbox coverage declaration (core/blackbox/coverage/capability.py) a LOCAL-mutating
    # registered tool must carry: scope, reversibility, snapshot strategy, receipt lifecycle,
    # rollback support, recorder. Left None by every builtin literal -- builtins seed through
    # core.blackbox.coverage.registry -- and REQUIRED for a plugin/MCP contract whose
    # side_effect_class is a local mutation (tool_registry refuses it otherwise).
    mutation: dict[str, Any] | None = None
    # The tool's own result IS the user-facing answer (an evidence report, a task-control
    # receipt): the tool loop publishes the grounded tool result and never asks a model to
    # narrate it. Declared, so no lane has to recognise the intent string.
    renders_final_answer: bool = False
    # Whether a MODEL may ever be offered this tool. False marks owner-only surfaces (an
    # operator authorization mint, an owner-local console act): they have a legal path -- the
    # owner-local surface that owns them -- but never a model-facing one, and the offer
    # census counts them under that owner path instead of demanding a model seat.
    model_visible: bool = True

    @property
    def read_only(self) -> bool:
        return self.side_effect_class == "read_only"


def _has_image_service() -> bool:
    """A sealed BYOK image credential (e.g. a fal.ai key) is itself the opt-in for image generation,
    so the tool un-gates without a separate policy flip. Lazy import keeps this contract module free
    of a media dependency at import time."""
    try:
        from core.media_tools import has_image_service

        return bool(has_image_service())
    except Exception:
        return False


def _hive_read_configured() -> bool:
    """Whether a Hive read path is actually wired: a watcher URL or a public bridge target.

    Mirrors core/execution/capabilities.py:38-41. Lazy import keeps this contract module free of a
    hive dependency at import time; any failure reads as not configured, which under-claims rather
    than over-claims.
    """

    try:
        from core.brain_hive_commons_state import load_public_hive_bridge_config
        from core.brain_hive_watch_config_loader import load_hive_activity_tracker_config

        watcher = load_hive_activity_tracker_config()
        bridge = load_public_hive_bridge_config()
        return bool(
            (watcher.enabled and watcher.watcher_api_url)
            or (bridge.enabled and bridge.topic_target_url)
        )
    except Exception:
        return False


def runtime_tool_contracts() -> list[RuntimeToolContract]:
    """The builtin contract list, with the product-edition floor applied.

    The edition floor is applied HERE — the single point every consumer of the
    builtin catalog crosses — so a floored capability (money lanes in VOOL
    School) is unsupported for every reader: never seated into an offer, typed
    ``disabled`` at direct dispatch, metadata-only in operator listings. It is
    re-evaluated on every call, so no late registration or preference change can
    outrun it (goal §4: NOT REGISTERED / NOT ROUTABLE / NOT INVOKABLE).
    """
    from core.code_assistant.contracts import with_step_argument_fields

    return _apply_edition_floor(with_step_argument_fields(_runtime_tool_contracts_raw()))


def _apply_edition_floor(
    contracts: list[RuntimeToolContract],
) -> list[RuntimeToolContract]:
    from dataclasses import replace

    from core.product_edition import (
        ProductEdition,
        active_edition,
        edition_allows,
        edition_intent_allowed,
    )

    if active_edition() is ProductEdition.PERSONAL:
        return contracts
    floored: list[RuntimeToolContract] = []
    for contract in contracts:
        ok, _ = edition_allows(contract.tool_surface)
        if ok:
            ok, _ = edition_intent_allowed(contract.intent)
        if ok:
            floored.append(contract)
            continue
        _, reason = edition_intent_allowed(contract.intent)
        if not reason:
            _, reason = edition_allows(contract.tool_surface)
        if not contract.supported and contract.unsupported_reason == reason:
            floored.append(contract)
            continue
        floored.append(
            replace(contract, supported=False, unsupported_reason=reason)
        )
    return floored


