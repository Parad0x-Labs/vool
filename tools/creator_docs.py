_GOOD_DETAILS = {
    "id": "alice/meeting-notes", "kind": "skill", "version": "1.0.0", "summary": "Turn meeting notes into a list of actions.",
    "category": "productivity", "subcategory": "meetings", "license": "MIT",
    "source": {"upload_id": "0" * 32, "namespace": "alice"},
}
# (what the author wrote, the change to a correct set of details)
_DETAIL_MISTAKES = (
    ("a field VOOL does not know (`colour`)", lambda v: v.__setitem__("colour", "blue")),
    ("a needed field left out (`license`)", lambda v: v.pop("license")),
    ("an id with capital letters or spaces", lambda v: v.__setitem__("id", "Alice Smith/Meeting Notes")),
    ("an id with no publisher part", lambda v: v.__setitem__("id", "meeting-notes")),
    ("a publisher name VOOL keeps (`vool/...`)", lambda v: (v.__setitem__("id", "vool/meeting-notes"),
                                                             v["source"].__setitem__("namespace", "vool"))),
    ("a kind that is not skill or plugin", lambda v: v.__setitem__("kind", "tool")),
    ("a version that is not three numbers", lambda v: v.__setitem__("version", "v1")),
    ("an empty summary", lambda v: v.__setitem__("summary", " ")),
    ("a summary over the length limit", lambda v: v.__setitem__("summary", "word " * 120)),
    ("an empty license", lambda v: v.__setitem__("license", "")),
    ("a title over the length limit", lambda v: v.__setitem__("title", "T" * 61)),
    ("a title with < or >", lambda v: v.__setitem__("title", "<b>Notes</b>")),
    ("release notes with a line break", lambda v: v.__setitem__("release_notes", "First line\nSecond line")),
    ("a category that is not on the list", lambda v: v.__setitem__("category", "everything")),
    ("a source that is neither an upload nor a GitHub commit", lambda v: v.__setitem__("source", {"url": "https://example.org"})),
    ("an upload source under another publisher's name", lambda v: v["source"].__setitem__("namespace", "bob")),
)


def detail_rows() -> list[tuple[str, str, str]]:
    """What ``core.registry.artifact.metadata`` says about each wrong detail: the reason and the fix."""
    from core.registry.artifact import metadata
    from core.registry.codec import RegistryError

    metadata(copy.deepcopy(_GOOD_DETAILS))   # the starting point itself is accepted, or no row means anything
    rows = []
    for what, change in _DETAIL_MISTAKES:
        value = copy.deepcopy(_GOOD_DETAILS)
        change(value)
        try:
            metadata(value)
        except RegistryError as refused:
            rows.append((what, str(refused), getattr(refused, "fix", "") or "(the reason is the whole answer)"))
        else:
            raise SystemExit(f"creator_docs: the details with {what} were accepted; the reference would be wrong")
    return rows


def _first_reason(findings: list[dict]) -> str:
    if not findings:
        raise SystemExit("creator_docs: a text that should be refused was accepted; the reference would be wrong")
    return str(findings[0].get("reason") or "")


def skill_rules() -> str:
    from core import skill_tools
    from core.registry import checks

    rule_rows = []
    for group, rules in (("every package", checks._RULES), ("every skill", checks._IMPORT_RULES)):
        for code, _pattern, reason in rules:
            rule_rows.append((_code(code), group, reason, checks.SKILL_FIXES.get(code) or reason.replace(
                "Skills on the Skill Codex can't", "VOOL skills can't")))
    other_rows = [
        (_code("invisible"), _first_reason(checks.skill_text_findings("Sort the list.​⁠ Then stop."))),
        (_code("too-long"), _first_reason(checks.skill_text_findings("word " * (checks.MAX_TEXT // 5 + 1)))),
        ("(no code)", checks._BOUNDARY_REASON),
        ("(no code)", checks.UNREADABLE),
    ]
    limits = [
        ("Instructions (the text below the header)", f"at most {skill_tools._MAX_BODY_CHARS:,} characters",
         skill_tools.plain_problem(f"body exceeds {skill_tools._MAX_BODY_CHARS} characters")),
        ("Name", f"at most {skill_tools.MAX_NAME_CHARS} characters", skill_tools.name_problem("x" * (skill_tools.MAX_NAME_CHARS + 1))),
        ("All text of one skill, for the safety check", f"under {checks.MAX_TEXT:,} characters", other_rows[1][1]),
        ("Instructions of a published skill", f"at least {checks.MIN_INSTRUCTIONS} characters",
         _card_answer({"id": "alice/meeting-notes", "summary": "Turn meeting notes into a list of actions."},
                      {"skills/meeting-notes/SKILL.md": "Sort the notes."})),
    ]
    timers = sorted(skill_tools.SCHEDULE_HEADER_KEYS)
    typed = list(skill_tools.TYPED_KEYS)
    return _page(
        "Skill rules: what a skill's text is checked by, and the settings VOOL reads",
        "A skill is text, so its rules are rules about words. Each rule has a short code, the sentence the "
        "Skill Codex shows, and the sentence VOOL shows when the skill comes in as a file, a zip or a draft "
        "(`python -m tools.community_skills try`, `zip` and `stage` print that one).",
        ["## Text rules", "",
         "\"every package\" rules read skills and plugin packages; \"every skill\" rules read skills only, "
         "whichever way they come in.", "",
         *_table(("Code", "Applies to", "Sentence on the Skill Codex", "Sentence when VOOL takes a skill in"), rule_rows)],
        ["## Other text checks", "", *_table(("Code", "Sentence"), other_rows)],
        ["## Limits", "", *_table(("What", "Limit", "Sentence when it is passed"), limits)],
        ["## Header settings VOOL reads", "",
         "The header is the block between the two `---` lines at the top of `SKILL.md`. These settings are read:", "",
         ", ".join(_code(key) for key in sorted(skill_tools.READ_HEADER_KEYS)) + ".", "",
         "Any other setting loads and changes nothing. The check says, for a setting named `colour`:", "",
         "> " + skill_tools.not_used({"colour": "blue"})[0]],
        ["## Timer settings", "", "These settings do nothing, because a skill never runs by itself:", "",
         ", ".join(_code(key) for key in timers) + ".", "",
         "The check says, for `schedule`:", "", "> " + skill_tools.not_used({"schedule": "daily"})[0]],
        ["## Settings only VOOL's own skills may set", "",
         ", ".join(_code(key) for key in typed) + ".", "",
         "A skill from outside that sets one is refused when imported as a zip or added from GitHub:", "",
         "> " + skill_tools.typed_keys_problem({typed[0]: "x"})],
        ["## Package details (`metadata.json`, kept as `registry.json` in the package)", "",
         "`python -m tools.community_skills init`, `lint` and `pack` print `{\"status\":\"refused\",\"reason\":...,\"fix\":...}` "
         "and exit 1 when a detail is wrong. `reason` is a short fixed phrase; `fix` says what to write.", "",
         *_table(("What the author wrote", "`reason`", "`fix`"), detail_rows())])


# ---------------------------------------------------------------- names kept back

def _card_answer(details: dict, files: dict | None = None) -> str:
    """What the Skill Codex's listing check says about these details, or "(accepted)"."""
    from core.registry import checks

    findings = checks._quality({"metadata": details, "manifest": {}}, files or {}, official=False)
    return " ".join(dict.fromkeys(str(item["reason"]) for item in findings)) or "(accepted)"


