#!/usr/bin/env python3
"""Write the creators' reference tables from the running code, or check that they are current.

    python -m tools.creator_docs --write
    python -m tools.creator_docs --check

Three files under ``docs/creators/reference/`` are produced, wholly from the code:

* ``plugin-refusals.md``: each common plugin mistake (``tools.plugin_mistakes``) is made to a copy of
  the example plugin and sent through the Add-ons page's own door in a throwaway profile; the row
  holds the sentence shown, the field named and what to write instead.
* ``skill-rules.md``: the rules a skill's text is checked by, the header settings VOOL reads, the
  timer settings that do nothing, and what the packaging step says about each wrong detail.
* ``names-kept-back.md``: the ids and names a plugin, a skill or a publisher may not use.

The same input gives the same bytes: rows are sorted or kept in the code's own order, and nothing
holds a date or a path of this computer. ``--check`` exits 1 and names each file that differs from
what the code produces now, so a changed rule with stale docs stops a build.
"""
from __future__ import annotations

import argparse
import contextlib
import copy
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

REFERENCE = Path("docs") / "creators" / "reference"
TEMPLATE = ROOT / "examples" / "plugins" / "template"
_OWN_PAGE = {"Content-Type": "application/json", "Host": "127.0.0.1:8123", "Origin": "http://127.0.0.1:8123"}
_PROFILE_SETTINGS = ("VOOL_HOME", "VOOL_PLUGIN_LIFECYCLE_PATH", "VOOL_PLUGINS_DIR", "VOOL_PLUGIN_SCRATCH_ROOT")


def _cell(text) -> str:
    """One table cell: on one line, with the bar that would end the cell written as its HTML code."""
    return " ".join(str(text).split()).replace("|", "&#124;")


def _table(head: tuple[str, ...], rows) -> list[str]:
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    lines += ["| " + " | ".join(_cell(item) for item in row) + " |" for row in rows]
    return lines


def _page(title: str, about: str, *parts: list[str]) -> str:
    lines = ["<!-- Generated by `python -m tools.creator_docs --write`. Do not edit by hand: change the code, then run it again. -->",
             "", "# " + title, "", about]
    for part in parts:
        lines += ["", *part]
    return "\n".join(lines) + "\n"


def _code(text) -> str:
    return "`" + str(text) + "`"


# ---------------------------------------------------------------- plugin refusals

def plugin_refusal_rows() -> list[dict]:
    """Every mistake in ``tools.plugin_mistakes``, answered by the door the Add-ons page posts to."""
    from tools.plugin_mistakes import MISTAKES

    kept = {name: os.environ.get(name) for name in _PROFILE_SETTINGS}
    profile = Path(tempfile.mkdtemp(prefix="vool-creator-docs-"))
    rows: list[dict] = []
    try:
        os.environ.update(VOOL_HOME=str(profile / "home"), VOOL_PLUGIN_LIFECYCLE_PATH=str(profile / "lifecycle.json"),
                          VOOL_PLUGINS_DIR=str(profile / "installed"), VOOL_PLUGIN_SCRATCH_ROOT=str(profile / "scratch"))
        from core.web.api.addon_api import handle_addon_post

        plain = json.loads((TEMPLATE / ".codex-plugin" / "plugin.json").read_text(encoding="utf-8"))
        for number, (what, change, _field, _words) in enumerate(MISTAKES):
            package = profile / "sources" / str(number)
            shutil.copytree(TEMPLATE, package)
            value = copy.deepcopy(plain)
            change(value)
            (package / ".codex-plugin" / "plugin.json").write_text(json.dumps(value, indent=2), encoding="utf-8")
            status, body = handle_addon_post({"action": "plugin_prepare", "path": str(package), "update": False},
                                             _OWN_PAGE, "127.0.0.1")
            note = body.get("maker_note") or {}
            if status != 400 or body.get("error") != "plugin_refused" or not note.get("fix"):
                raise SystemExit(f"creator_docs: the mistake {what!r} was not refused with a note for the maker: {body}")
            rows.append({"mistake": what, "sentence": body["message"], "where": note.get("where", ""), "fix": note["fix"]})
    finally:
        for name, value in kept.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value
        # VOOL seals what it captures; give the write bits back to this run's own folder before removing it.
        for directory, folders, files in os.walk(profile):
            for name in (*folders, *files):
                with contextlib.suppress(OSError):
                    target = Path(directory) / name
                    if not target.is_symlink():
                        target.chmod(0o700)
        shutil.rmtree(profile, ignore_errors=True)
    return rows


def plugin_refusals() -> str:
    rows = plugin_refusal_rows()
    return _page(
        "Plugin refusals: what was written, what VOOL says, what to write instead",
        "Each row is one mistake made to the example plugin's setup file (`.codex-plugin/plugin.json` in "
        "`examples/plugins/template`) and checked the way the Add-ons page checks a folder. "
        "`python -m tools.plugin_check FOLDER --json` prints the same answer for your folder: "
        "`message` is the sentence shown, `where` is the field, `fix` is what to write instead. "
        f"Rows: {len(rows)}.",
        _table(("What the maker did", "Sentence shown (`message`)", "Field (`where`)", "What to write instead (`fix`)"),
               [(row["mistake"], row["sentence"], _code(row["where"]), row["fix"]) for row in rows]))


