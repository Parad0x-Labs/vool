# ---------------------------------------------------------------- write and check

PAGES = (("plugin-refusals.md", plugin_refusals), ("skill-rules.md", skill_rules), ("names-kept-back.md", names_kept_back))


# Settings that point VOOL at another folder of shipped packs. The reference names the packs this
# checkout ships, so a run inside a test session or a customised shell writes the same bytes.
_PACK_SETTINGS = ("VOOL_BUNDLED_PLUGINS_DIR",)


def build() -> dict[str, str]:
    """{file name: text} for every generated page, as the code produces it now."""
    kept = {name: os.environ.pop(name, None) for name in _PACK_SETTINGS}
    try:
        return {name: make() for name, make in PAGES}
    finally:
        os.environ.update({name: value for name, value in kept.items() if value is not None})


def stale(root: Path = ROOT) -> list[str]:
    """Names of the generated files that are missing under ``root`` or differ from the code."""
    wrong = []
    for name, text in build().items():
        target = Path(root) / REFERENCE / name
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            wrong.append(name)
    return wrong


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="creator_docs", description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the reference files")
    mode.add_argument("--check", action="store_true", help="exit 1 when a file differs from what the code produces now")
    parser.add_argument("--root", type=Path, default=ROOT, help="the checkout whose docs are written or checked (default: this one)")
    args = parser.parse_args(argv)
    if args.write:
        folder = args.root / REFERENCE
        folder.mkdir(parents=True, exist_ok=True)
        for name, text in build().items():
            (folder / name).write_text(text, encoding="utf-8")
            print("wrote " + (REFERENCE / name).as_posix())
        return 0
    wrong = stale(args.root)
    for name in wrong:
        print("stale: " + (REFERENCE / name).as_posix() + " differs from the code. Run: python -m tools.creator_docs --write")
    if not wrong:
        print(f"current: {len(PAGES)} reference files match the code")
    return 1 if wrong else 0


if __name__ == "__main__":
    raise SystemExit(main())
