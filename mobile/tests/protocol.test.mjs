test("FIPS 180-4 SHA-256 known answers", () => {
  assert.equal(toHex(sha256(new TextEncoder().encode("abc"))),
    "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
  assert.equal(toHex(sha256(new TextEncoder().encode(""))),
    "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
  assert.equal(toHex(sha256(new TextEncoder().encode("a".repeat(1000)))),
    "41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3");
});

test("randomized HMAC cross-check vs node:crypto (100 rounds)", () => {
  for (let i = 0; i < 100; i++) {
    const key = new Uint8Array(1 + ((i * 7) % 128));
    const msg = new Uint8Array(1 + ((i * 13) % 300));
    globalThis.crypto.getRandomValues(key);
    globalThis.crypto.getRandomValues(msg);
    const expected = createHmac("sha256", Buffer.from(key)).update(Buffer.from(msg)).digest("hex");
    assert.equal(toHex(hmacSha256(key, msg)), expected, `round ${i}`);
  }
});

