test("verifyDesktopProof: pinned fingerprint + valid signature (self-signed fixture)", () => {
  const kp = generateDeviceKeypair(); // stands in for the desktop authority
  const fp = toHex(sha256(hexToBytes(kp.publicKeyHex)));
  const payload = {
    kind: "vool.mobile.pairing.claim.v1",
    pairing_id: "pair_x",
    device_id: "phone:y",
    grant_id: "g",
    desktop_fingerprint: fp,
  };
  const signature = toHex(signBytes(kp.secretKeyHex, canonicalBytes(payload)));
  const good = verifyDesktopProof({ payload, signature }, fp, kp.publicKeyHex);
  assert.deepEqual(good, { pinnedMatches: true, signatureValid: true });
  // signature is valid, but the QR pin names a DIFFERENT desktop: refuse
  const otherKp = generateDeviceKeypair();
  const otherFp = toHex(sha256(hexToBytes(otherKp.publicKeyHex)));
  const evil = verifyDesktopProof({ payload, signature }, otherFp, kp.publicKeyHex);
  assert.equal(evil.pinnedMatches, false);
  // pin matches, but the response carries a key that does not hash to it
  const swappedKey = verifyDesktopProof({ payload, signature }, fp, otherKp.publicKeyHex);
  assert.equal(swappedKey.pinnedMatches, false);
  // tampered payload: pin matches, signature fails
  const tampered = verifyDesktopProof(
    { payload: { ...payload, device_id: "phone:evil" }, signature }, fp, kp.publicKeyHex);
  assert.equal(tampered.signatureValid, false);
});

function hexToBytes(hex) {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}


test("the QR and the connection address parse on React Native's stub URL", () => {
  // React Native 0.76's URL throws "URL.hostname is not implemented" (and the same for port,
  // protocol, search and searchParams). Node's full URL hid that: on a phone every pairing QR failed.
  const RealURL = globalThis.URL;
  globalThis.URL = class {
    constructor(href) { this.href = String(href); }
    get hostname() { throw new Error("URL.hostname is not implemented"); }
    get port() { throw new Error("URL.port is not implemented"); }
    get protocol() { throw new Error("URL.protocol is not implemented"); }
    get searchParams() { throw new Error("URL.searchParams is not implemented"); }
    toString() { return this.href; }
  };
  try {
    const fp = "cd".repeat(32);
    const exp = Math.floor(Date.now() / 1000) + 300;
    const parsed = parsePairingUri(`vool-pair://192.168.2.207:55822?fp=${fp}&pid=pair_0f5870f592a049b4&code=M7XRA5X7&exp=${exp}`);
    assert.ok(parsed);
    assert.equal(parsed.host, "192.168.2.207");
    assert.equal(parsed.port, 55822);
    assert.equal(parsed.pairingId, "pair_0f5870f592a049b4");
    assert.equal(connectionAddress("http://192.168.2.207:55822/"), "http://192.168.2.207:55822");
    assert.equal(connectionAddress(`https://relay.example/rooms/${"a".repeat(48)}`), `https://relay.example/rooms/${"a".repeat(48)}`);
    for (const bad of ["http://example.com:80", "ftp://192.168.1.2", "http://user:pw@192.168.1.2", "http://192.168.1.2/?x=1",
      "http://192.168.1.2/#x", "http://192.168.1.2/other", "http://192.168.1.2:70000"]) {
      assert.throws(() => connectionAddress(bad), /Invalid connection address/, bad);
    }
    assert.equal(parsePairingUri(`vool-pair://h:99999?fp=${fp}&pid=pair_ab&code=M7XRA5X7&exp=${exp}`), null);
  } finally {
    globalThis.URL = RealURL;
  }
});

test("a file the computer sent arrives whole from its pieces", async () => {
  const { MobileCompanionClient } = await import("../src/protocol/client.ts");
  const bytes = Uint8Array.from({ length: 2000 }, (_, i) => (i * 7) % 256);
  const piece = 768; // the desktop's pieces are a multiple of 3 bytes
  const asked = [];
  const fetchImpl = async (_url, init) => {
    const body = JSON.parse(init.body);
    asked.push(body.params.offset);
    const start = body.params.offset;
    const data = bytes.slice(start, start + piece);
    const result = {
      file: { id: "out_" + "a".repeat(32), name: "day4.jpg", media_type: "image/jpeg", size_bytes: bytes.length },
      offset: start, next_offset: start + data.length, done: start + data.length >= bytes.length,
      content_b64: Buffer.from(data).toString("base64"),
    };
    return { status: 200, json: async () => ({ ok: true, result }) };
  };
  const client = new MobileCompanionClient({
    deviceId: "dev", grantId: "g", grantSecret: "s", baseUrl: "http://127.0.0.1:1", desktopFingerprint: "f",
    deviceSeedHex: "11".repeat(32),
  }, { fetchImpl });
  const got = await client.fetchSentFile("out_" + "a".repeat(32));
  assert.deepEqual(asked, [0, 768, 1536]);
  assert.deepEqual(new Uint8Array(Buffer.from(got.base64, "base64")), bytes);
});

// The phone hands this work to native code (FastCrypto.java); these answers were checked against it too.
import { fast, scriptCrypto, setFastCrypto } from "../src/protocol/fast.ts";
import { sealBody, openBody } from "../src/protocol/sealed.ts";

const FAST_VECTOR = {
  text: "c\n\u{1F600}\n\né{\u{1F600}b\"\u{1F600}b\n\nb\n\u{1F600}c{{",
  key: "686be7a68a8543e901f84c606255801f5046b992e20b35fa59e535282d4ff23d",
  nonce: "734338ee326a46c0496cea5d59054553e0b7d92060002446",
  sealed: "rItwyJmFRjLjrSDc8VFrF5cfiCqYAa137/Vx264Gi8qtUmHUInMJbH1F4Gnr1l8BTA==",
};

test("link sealing and hashing over text give the same bytes as before", () => {
  const v = FAST_VECTOR;
  assert.equal(scriptCrypto.seal(v.text, v.nonce, v.key), v.sealed);
  assert.equal(scriptCrypto.open(v.sealed, v.nonce, v.key), v.text);
  const tampered = Buffer.from(v.sealed, "base64"); tampered[20] ^= 1;
  assert.equal(scriptCrypto.open(tampered.toString("base64"), v.nonce, v.key), null);
  assert.equal(scriptCrypto.sha256Hex(v.text), createHash("sha256").update(v.text, "utf8").digest("hex"));
  assert.equal(scriptCrypto.hmacSha256Hex("", v.text), createHmac("sha256", Buffer.alloc(0)).update(v.text, "utf8").digest("hex"));
  assert.equal(scriptCrypto.hmacSha256Hex("k".repeat(90), v.text), createHmac("sha256", "k".repeat(90)).update(v.text, "utf8").digest("hex"));
  // the request proof digests the params the same way as the byte path did
  const params = {action: "capture.chunk", data: "QUJD".repeat(1000), note: "café"};
  const args = {deviceId: "phone:1", action: "capture.chunk", params, nonce: "n", timestamp: "t", grantId: "g"};
  const expected = canonicalJson({kind: "vool.mobile.request.v1", device_id: "phone:1", action: "capture.chunk",
    params_sha256: toHex(sha256(canonicalBytes(params))), nonce: "n", timestamp: "t", grant_id: "g"});
  assert.equal(new TextDecoder().decode(requestProofPayload(args)), expected);
});

test("sealed bodies go through the native side when it is there", () => {
  const shared = new Uint8Array(32).fill(7);
  const calls = [];
  setFastCrypto({
    sha256Hex: t => (calls.push("sha"), scriptCrypto.sha256Hex(t)),
    hmacSha256Hex: (k, t) => (calls.push("hmac"), scriptCrypto.hmacSha256Hex(k, t)),
    seal: (t, n, k) => (calls.push("seal"), scriptCrypto.seal(t, n, k)),
    open: (d, n, k) => (calls.push("open"), scriptCrypto.open(d, n, k)),
  });
  try {
    const envelope = sealBody({kind: "x", body: {a: "é"}}, shared, "response", new Uint8Array(24).fill(1));
    assert.deepEqual(openBody(envelope, shared, "response"), {kind: "x", body: {a: "é"}});
    assert.deepEqual(calls, ["seal", "open"]);
    assert.throws(() => openBody({...envelope, ciphertext: envelope.ciphertext.replace(/^./, c => c === "A" ? "B" : "A")}, shared, "response"),
      /authentication failed/);
    assert.throws(() => openBody({...envelope, nonce: "00"}, shared, "response"), /nonce/);
  } finally { setFastCrypto(null); }
  assert.equal(fast.seal(FAST_VECTOR.text, FAST_VECTOR.nonce, FAST_VECTOR.key), FAST_VECTOR.sealed);
});
