// Protocol-core unit tests — run with:  node --test tests/protocol.test.mjs
// (from mobile/). Pure Node: the SAME source files the React Native app ships.
//
// The canonical-JSON and HMAC vectors are golden in both directions: the
// canonical bytes are pinned against the desktop's Python implementation
// (json.dumps sort_keys+separators, ensure_ascii default) and the HMAC/SHA
// primitives against node:crypto. The TS client signing the exact payload the
// Python authority verifies is the load-bearing cross-check of this whole
// lane — if either side drifts, pairing dies, so it is tested directly.
