test("keypair is deterministic from its seed; device_id derives from the public key", () => {
  const a = generateDeviceKeypair();
  const again = keypairFromSeed(a.seedHex);
  assert.equal(a.publicKeyHex, again.publicKeyHex);
  assert.equal(a.secretKeyHex, again.secretKeyHex);
  assert.equal(deviceIdFor(a.publicKeyHex).slice(0, 6), "phone:");
  assert.equal(deviceIdFor(a.publicKeyHex), deviceIdFor(again.publicKeyHex));
  const other = generateDeviceKeypair();
  assert.notEqual(deviceIdFor(a.publicKeyHex), deviceIdFor(other.publicKeyHex));
});

test("verifyDesktopProof: pinned fingerprint + valid signature (self-signed fixture)", () => {
  const kp = generateDeviceKeypair(); // stands in for the desktop authority
  const fp = toHex(sha256(hexToBytes(kp.publicKeyHex)));
  const payload = {
    kind: "vool.mobile.pairing.claim.v1",
    pairing_id: "pair_x",
    device_id: "phone:y",
    grant_id: "g",
    desktop_fingerprint: fp,
  };
  const signature = toHex(signBytes(kp.secretKeyHex, canonicalBytes(payload)));
  const good = verifyDesktopProof({ payload, signature }, fp, kp.publicKeyHex);
  assert.deepEqual(good, { pinnedMatches: true, signatureValid: true });
  // signature is valid, but the QR pin names a DIFFERENT desktop: refuse
  const otherKp = generateDeviceKeypair();
  const otherFp = toHex(sha256(hexToBytes(otherKp.publicKeyHex)));
  const evil = verifyDesktopProof({ payload, signature }, otherFp, kp.publicKeyHex);
  assert.equal(evil.pinnedMatches, false);
  // pin matches, but the response carries a key that does not hash to it
  const swappedKey = verifyDesktopProof({ payload, signature }, fp, otherKp.publicKeyHex);
  assert.equal(swappedKey.pinnedMatches, false);
  // tampered payload: pin matches, signature fails
  const tampered = verifyDesktopProof(
    { payload: { ...payload, device_id: "phone:evil" }, signature }, fp, kp.publicKeyHex);
  assert.equal(tampered.signatureValid, false);
});

function hexToBytes(hex) {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}
