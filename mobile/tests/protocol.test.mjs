test("Ed25519: sign/verify roundtrip + wrong key refuses (vendored tweetnacl)", () => {
  const a = generateDeviceKeypair();
  const b = generateDeviceKeypair();
  const msg = new TextEncoder().encode("vool mobile companion");
  const sig = signBytes(a.secretKeyHex, msg);
  assert.ok(verifyBytes(a.publicKeyHex, msg, sig));
  assert.ok(!verifyBytes(b.publicKeyHex, msg, sig));
  assert.ok(!verifyBytes(a.publicKeyHex, new TextEncoder().encode("tampered"), sig));
  // cross-check the seed handling: same seed -> same identity
  const again = generateDeviceKeypair();
  assert.notEqual(a.publicKeyHex, again.publicKeyHex);
});

test("Ed25519 cross-impl: Node WebCrypto verifies a tweetnacl signature", async () => {
  // (Node's WebCrypto refuses raw-importing an Ed25519 PRIVATE key, so the
  // independent implementation verifies while the vendored one signs.)
  const kp = generateDeviceKeypair();
  const msg = new TextEncoder().encode("cross implementation");
  const sig = signBytes(kp.secretKeyHex, msg);
  const pub = new Uint8Array(32);
  for (let i = 0; i < 32; i++) pub[i] = parseInt(kp.publicKeyHex.slice(i * 2, i * 2 + 2), 16);
  const webKey = await globalThis.crypto.subtle.importKey("raw", pub, { name: "Ed25519" }, false, ["verify"]);
  const ok = await globalThis.crypto.subtle.verify({ name: "Ed25519" }, webKey, sig, msg);
  assert.ok(ok);
});

test("parsePairingUri accepts a well-formed QR payload and refuses tampering", () => {
  const fp = "ab".repeat(32);
  const exp = Math.floor(Date.now() / 1000) + 300;
  const uri = `vool-pair://192.168.1.20:11435?fp=${fp}&pid=pair_4afb7b0c52cc81f6&code=M7XRA5X7&exp=${exp}`;
  const parsed = parsePairingUri(uri);
  assert.ok(parsed);
  assert.equal(parsed.host, "192.168.1.20");
  assert.equal(parsed.port, 11435);
  assert.equal(parsed.desktopFingerprint, fp);
  assert.equal(parsed.code, "M7XRA5X7");
  assert.equal(parsed.expiresAtEpoch, exp);
  assert.ok(pairingUriIsFresh(parsed));
  assert.ok(!pairingUriIsFresh({ ...parsed, expiresAtEpoch: Math.floor(Date.now() / 1000) - 1 }));
  assert.equal(parsePairingUri("http://not-a-pair-uri"), null);
  assert.equal(parsePairingUri(`vool-pair://h?fp=zz&pid=pair_abc&code=AAAAAAAA&exp=${exp}`), null); // fp not hex64
  assert.equal(parsePairingUri(`vool-pair://h?fp=${fp}&pid=wrong&code=M7XRA5X7&exp=${exp}`), null);
  assert.equal(parsePairingUri(`vool-pair://h?fp=${fp}&pid=pair_4afb7b0c52cc81f6&code=0OI1L&exp=${exp}`), null); // ambiguous chars
  assert.equal(parsePairingUri(`vool-pair://h?fp=${fp}&pid=pair_4afb7b0c52cc81f6&code=M7XRA5X7&exp=not-a-number`), null);
  // tampered expiry (past) parses but refuses as stale
  const stale = parsePairingUri(`vool-pair://h?fp=${fp}&pid=pair_4afb7b0c52cc81f6&code=M7XRA5X7&exp=1000`);
  assert.ok(stale && !pairingUriIsFresh(stale));
});

