"""The creators' pages say what the code says, word for word.

A maker (or an agent building for one) looks a refusal up by its sentence. A page that quotes a sentence
VOOL no longer says sends them looking for a rule that is not there. Two things are held here:

* the three reference tables under ``docs/creators/reference`` are exactly what ``tools.creator_docs``
  produces from the code now, so a rule whose wording changed fails until the tables are written again;
* every VOOL message quoted on the agents' lookup page (``docs/creators/agents/errors.md``) exists in the
  code's own text or in those tables.
"""
from __future__ import annotations

import ast
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CREATORS = ROOT / "docs" / "creators"
ERRORS_PAGE = CREATORS / "agents" / "errors.md"
REFERENCE = CREATORS / "reference"
GENERATED = ("plugin-refusals.md", "skill-rules.md", "names-kept-back.md")
# Where the sentences a maker can meet are written.
SOURCES = (
    "core/plugin_identity.py", "core/plugin_manifest.py", "core/plugin_migration.py", "core/plugin_manager.py",
    "core/plugin_lifecycle.py", "core/registry/checks.py", "core/registry/artifact.py", "core/skill_tools.py",
    "core/skill_frontmatter.py", "core/skill_package.py", "tools/community_skills.py", "tools/community_skills_try.py", "tools/plugin_check.py",
)
_FENCE = re.compile(r"^```.*?^```", re.MULTILINE | re.DOTALL)
_SPAN = re.compile(r"`([^`\n]+)`|\"([^\"\n]+)\"")


def _generator(*arguments: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, "-m", "tools.creator_docs", *arguments], cwd=ROOT, capture_output=True,
                          text=True, timeout=300, check=False)


def _code_text() -> list[str]:
    """Every piece of text the listed sources hold, as Python reads it (a sentence split over lines is one)."""
    found: list[str] = []
    for name in SOURCES:
        tree = ast.parse((ROOT / name).read_text(encoding="utf-8"))
        found += [node.value for node in ast.walk(tree) if isinstance(node, ast.Constant) and isinstance(node.value, str)]
    catalog = json.loads((ROOT / "core" / "i18n" / "catalogs" / "en.json").read_text(encoding="utf-8"))

    def strings(value):
        if isinstance(value, dict):
            for item in value.values():
                yield from strings(item)
        elif isinstance(value, str):
            yield value

    found += list(strings(catalog))
    found += [(REFERENCE / name).read_text(encoding="utf-8").replace("&#124;", "|") for name in GENERATED]
    return found


def quoted_messages(page: str) -> list[str]:
    """What the page presents as VOOL's words: text in backticks or double quotes that reads as a sentence.

    A field name, a rule code or a file name is one or two words; a command starts with ``python``; a JSON
    example starts with a brace. Everything else of four words or more is a message.
    """
    spans = [first or second for first, second in _SPAN.findall(_FENCE.sub("", page))]
    return [span.strip() for span in spans
            if len(span.split()) >= 4 and not span.lstrip().startswith(("python ", "{", "PYTHONPATH"))]


def missing_messages(page: str, corpus: list[str]) -> list[str]:
    """The quoted messages no source holds. ``...`` in a quote stands for a part that varies."""
    missing = []
    for message in quoted_messages(page):
        parts = [part.strip() for part in message.split("...") if len(part.split()) >= 2]
        if not parts or not all(any(part in text for text in corpus) for part in parts):
            missing.append(message)
    return missing


def test_the_reference_tables_are_what_the_code_produces_now():
    result = _generator("--check")
    assert result.returncode == 0, result.stdout + result.stderr
    for name in GENERATED:
        lines = (REFERENCE / name).read_text(encoding="utf-8").splitlines()
        assert lines[0].startswith("# "), name + ": the docs site reads the first line as the page title"
        assert "Generated by `python -m tools.creator_docs --write`" in lines[2], name


def test_a_table_that_differs_from_the_code_fails_the_check(tmp_path):
    shutil.copytree(REFERENCE, tmp_path / "docs" / "creators" / "reference")
    assert _generator("--check", "--root", str(tmp_path)).returncode == 0
    stale = tmp_path / "docs" / "creators" / "reference" / "skill-rules.md"
    text = stale.read_text(encoding="utf-8")
    assert "Take the address out." in text
    stale.write_text(text.replace("Take the address out.", "Remove the address.", 1), encoding="utf-8")
    result = _generator("--check", "--root", str(tmp_path))
    assert result.returncode == 1 and "stale: docs/creators/reference/skill-rules.md" in result.stdout, result.stdout
    (tmp_path / "docs" / "creators" / "reference" / "names-kept-back.md").unlink()
    assert "names-kept-back.md" in _generator("--check", "--root", str(tmp_path)).stdout, "a missing table is stale too"


def _temp_roots() -> set[str]:
    """This computer's temp folders as the system names them, followed through links."""
    import os

    found = {tempfile.gettempdir()}
    if hasattr(os, "confstr"):
        try:
            found.add(os.confstr("CS_DARWIN_USER_TEMP_DIR") or "")
        except (ValueError, OSError):
            pass
    roots = {str(Path(item).resolve()) for item in found if item} | {item.rstrip("/") for item in found if item}
    return {root for root in roots if len(root) > 4}


def test_the_tables_hold_no_date_and_no_path_of_this_computer():
    for name in GENERATED:
        text = (REFERENCE / name).read_text(encoding="utf-8")
        assert str(ROOT) not in text and str(Path.home()) not in text, name
        assert not re.search(r"\b20\d\d-\d\d-\d\d\b|/tmp/", text), name
        for temp in _temp_roots():
            assert temp not in text, (name, temp)


def test_every_message_the_errors_page_quotes_is_one_vool_says():
    page = ERRORS_PAGE.read_text(encoding="utf-8")
    quoted = quoted_messages(page)
    assert len(quoted) >= 15, "the page holds the fifteen most common messages inline"
    assert missing_messages(page, _code_text()) == []


def test_a_sentence_vool_does_not_say_is_caught():
    corpus = _code_text()
    page = ERRORS_PAGE.read_text(encoding="utf-8")
    known = "This name belongs to a plugin made by VOOL."
    assert known in page
    changed = page.replace(known, "This name is owned by a plugin from VOOL.")
    assert missing_messages(changed, corpus) and missing_messages(page, corpus) == []
    for name in GENERATED:
        assert (CREATORS / "reference" / name).name in page, f"the errors page links to {name}"
