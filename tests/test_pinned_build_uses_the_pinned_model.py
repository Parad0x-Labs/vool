def test_a_pinned_build_generates_through_the_pinned_provider(agent) -> None:
    calls: list[str] = []

    def invoke_manifest(*, manifest, request, output_mode, task, source_context):
        calls.append(str(manifest.model_name))
        return None, SimpleNamespace(output_text="def median(values): ..."), None

    recorder = _Recorder()
    result = _run(
        agent,
        ctx=_context(pinned=True),
        build_app_from_spec=recorder,
        invoke_manifest=invoke_manifest,
        manifest=_manifest(),
    )

    assert calls == [PINNED], f"the build generated on {calls!r}, not on the operator's model"
    assert recorder.generated == ["def median(values): ..."]
    assert LOCAL_TAG not in str(result.get("response") or "")


def test_the_pinned_request_survives_the_real_prompt_budget(agent) -> None:
    """The shape of the request, checked against the real gate that rejected it.

    Found live, not in review. The first pinned build reaching a provider failed on EVERY
    generation with `prompt_budget_exceeded: protected system prompt and current turn require 166
    tokens, but only 16384 are available` and `system_prompt_preserved: false`. 166 of 16384 is not
    a size problem: the request carried a pre-built `messages=[{"role": "user", ...}]`, so the
    protected system instructions were absent from the list and `core/prompt_budget.py` fails closed
    on that regardless of length. A mock provider cannot see this -- so the captured request is run
    through the real budget function here.
    """
    from adapters.openai_compatible_adapter import _request_messages_with_memory

    captured: list = []

    def invoke_manifest(*, manifest, request, output_mode, task, source_context):
        captured.append(request)
        return None, SimpleNamespace(output_text="def median(values): ..."), None

    _run(
        agent,
        ctx=_context(pinned=True),
        build_app_from_spec=_Recorder(),
        invoke_manifest=invoke_manifest,
        manifest=_manifest(),
    )

    assert captured, "no request ever reached the provider"
    messages = _request_messages_with_memory(
        captured[0],
        context_window=24576,
        output_reserve_tokens=8192,
    )
    assert any(str(m.get("role")) == "system" for m in messages), (
        "the builder's system instructions never reach the message list, so prompt_budget rejects "
        "every generation of the build"
    )


