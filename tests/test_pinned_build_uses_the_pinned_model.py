PINNED_PAID = "z-ai/glm-5.3-flash"


def _paid_manifest() -> SimpleNamespace:
    """A manifest the paid gate itself classifies as paid_cloud (explicit metadata wins)."""
    return SimpleNamespace(
        provider_id="openrouter-byok:" + PINNED_PAID,
        model_name=PINNED_PAID,
        metadata={"cost_class": "paid_cloud"},
    )


def _authorization() -> SimpleNamespace:
    return SimpleNamespace(
        model_call_id="model-call-paid-build-1",
        provider_id="openrouter-byok:" + PINNED_PAID,
    )


class _EmptyRecorder(_Recorder):
    def __init__(self) -> None:
        super().__init__(files=())


def test_a_paid_pinned_build_dispatches_under_a_reservation(agent) -> None:
    """The builder used to arrive at `_invoke_manifest` with no `authorized_paid_call`, so every
    generation of every pinned paid build refused with `paid_call_not_authorized_or_reserved`
    before any request was sent. The generation must now carry a reservation from the same
    authority the router's own pick lane uses."""
    authorization = _authorization()
    contexts: list[dict] = []

    def invoke_manifest(*, manifest, request, output_mode, task, source_context):
        contexts.append(dict(source_context))
        return None, SimpleNamespace(output_text="def main(): ..."), None

    recorder = _Recorder()
    with mock.patch(
        "core.paid_call_reservation.reserve_owner_pick_paid_call",
        return_value=authorization,
    ) as reserve:
        result = _run(
            agent,
            ctx=_context(pinned=True, model=PINNED_PAID),
            build_app_from_spec=recorder,
            invoke_manifest=invoke_manifest,
            manifest=_paid_manifest(),
        )

    assert recorder.generated == ["def main(): ..."], "the build did not generate on the pinned model"
    assert reserve.call_count == 1
    reserved_kwargs = reserve.call_args.kwargs
    assert reserved_kwargs["manifest"] is not None
    assert reserved_kwargs["call_role"] == "answer_generation"
    assert contexts and contexts[0].get("authorized_paid_call") is authorization
    assert contexts[0].get("model_call_role") == "answer_generation"
    assert PINNED_PAID in str(result.get("response") or "")
    assert result.get("success") is not False, "a dispatched build is not a failure"


def test_a_refused_paid_reservation_names_the_denial_and_contacts_no_provider(agent) -> None:
    """The caps' own refusal code reaches the operator, the provider is stated as not contacted,
    and the turn closes FAILED -- a refused build is not a completed one."""

    def invoke_manifest(**kwargs):  # pragma: no cover - the assertion is the point
        raise AssertionError("a refused reservation must never reach the provider")

    def denying(*, denial, **kwargs):
        denial["reason"] = "daily_spend_cap_exceeded"
        return None

    with mock.patch(
        "core.paid_call_reservation.reserve_owner_pick_paid_call",
        side_effect=denying,
    ):
        result = _run(
            agent,
            ctx=_context(pinned=True, model=PINNED_PAID),
            build_app_from_spec=_EmptyRecorder(),
            invoke_manifest=invoke_manifest,
            manifest=_paid_manifest(),
        )

    response = str(result.get("response") or "")
    assert PINNED_PAID in response
    assert "daily_spend_cap_exceeded" in response, "the refusal must name the authority's own code"
    assert "provider was not contacted" in response
    assert result.get("success") is False
    assert result.get("route_reason") == "builder_pinned_model_produced_nothing"
    refusal_details = dict((result.get("details") or {}).get("builder_pinned_refusal") or {})
    assert refusal_details.get("provider_contacted") is False


