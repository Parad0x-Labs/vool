@pytest.mark.parametrize(
    "request_text",
    [
        "build me a telegram bot",
        "create a cli tool for parsing logs",
        "scaffold a fastapi service in the workspace",
    ],
)
def test_the_builder_gate_admits_a_pinned_turn(agent, request_text: str) -> None:
    """Verbatim the requests that used to be refused. Pinned and unpinned must now agree."""

    classification = {"task_class": "system_design"}
    with mock.patch("core.policy_engine.get", return_value=True):
        unpinned = agent._should_run_builder_controller(
            effective_input=request_text,
            classification=classification,
            source_context=_context(pinned=False),
        )
        pinned = agent._should_run_builder_controller(
            effective_input=request_text,
            classification=classification,
            source_context=_context(pinned=True),
        )

    assert unpinned is True
    assert pinned is True, (
        f"{request_text!r} was refused with {PINNED} pinned; the operator gets "
        '"I couldn\'t map that cleanly to a real action" instead of a build'
    )


