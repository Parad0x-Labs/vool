"""A build on a pinned turn must WORK, and the files must come from the pinned model.

Both halves matter and they used to be traded against each other.

`builder/controller.py::build_ollama_generate_fn` posts straight to Ollama's `/api/chat` with the
runtime's LOCAL tag, so on a pinned turn every file a build wrote would have been generated by
`qwen3:8b` and attributed to whatever the operator selected. That was prevented by refusing the turn
outright in `_should_run_builder_controller`:

    if explicit_model_owns_semantic_turn(source_context):
        return False

Measured on the installed build, that refusal did not produce a refusal. The turn fell through to the
selected model's tool loop, the model did not call `workspace.write_file`, and

    i need <ws>/v5/median.py with a median function

came back "I couldn't map that cleanly to a real action" after 75.6s -- verbatim, with 0 files on
disk. Pinning a model meant you could not build.

So the substitution is now prevented where it happens rather than by refusing the feature:
`_run_model_build` asks `pinned_generation` for a generate_fn backed by the SELECTED provider. The
tests below drive that seam rather than asserting the shape of the source, because the failure this
guards against is a silent swap and a swap is only visible in which provider was actually called.
"""
from __future__ import annotations

from types import SimpleNamespace
from unittest import mock

import pytest

from core.agent_runtime.builder import controller as agent_builder_controller
from core.agent_runtime.builder import pinned_generation

PINNED = "nvidia/nemotron-3-ultra-550b-a55b:free"
LOCAL_TAG = "qwen3:8b"


@pytest.fixture(scope="module")
def agent():
    from apps.vool_agent import VoolAgent

    return VoolAgent(backend_name="test-backend", device="openclaw-test", persona_id="default")


def _context(*, pinned: bool, workspace: str = "/tmp/ws", model: str = PINNED) -> dict[str, object]:
    ctx: dict[str, object] = {
        "workspace": workspace,
        "workspace_root": workspace,
        "operating_mode": "auto",
        "surface": "api",
    }
    if pinned:
        ctx["requested_model"] = model
    return ctx


def _manifest() -> SimpleNamespace:
    return SimpleNamespace(provider_id="openrouter-byok:" + PINNED, model_name=PINNED)


class _Recorder:
    """Stands in for the build itself: calls generate_fn once and reports one file written."""

    def __init__(self, *, files: tuple[str, ...] = ("median.py",)) -> None:
        self.generated: list[str] = []
        self.files = files

    def __call__(self, *, request, target_rel, source_context, generate_fn, run_tool_fn, **kwargs):
        # `**kwargs` absorbs the prove-it fields (expected_test_outcome, subject_paths) that the
        # real signature grew. These tests are about WHICH MODEL wrote the files, not about the
        # test verdict, so they should not have to track every new build parameter.
        self.generated.append(generate_fn("write median.py"))
        return SimpleNamespace(
            target_dir=target_rel,
            files_written=list(self.files),
            files_skipped=[],
            file_lines={},
            tests_ran=False,
            tests_passed=False,
            fix_rounds=0,
            expected_test_outcome=str(kwargs.get("expected_test_outcome") or "unspecified"),
            subject_paths=tuple(kwargs.get("subject_paths") or ()),
            test_returncode=None,
            test_command="",
            proof_failed=False,
            test_output="",
            handled=True,
            error="",
            # The mutation-authority fields the real report carries. Kept in step deliberately:
            # `_run_model_build` puts them in the turn's change ledger, so a double that omits them
            # makes this file fail on a lane it does not test (see builder/mutation_scope.py).
            scope_kind="open",
            authorized_paths=(),
            paths_refused=[],
            commands_refused=[],
        )


def _run(agent, *, ctx, build_app_from_spec, invoke_manifest, manifest):
    """Drive `_run_model_build` with the model lane stubbed, and return its result dict."""
    task = SimpleNamespace(task_id="task-pinned-build")
    with (
        mock.patch.object(
            agent.memory_router, "_requested_model_manifest", return_value=manifest
        ),
        mock.patch.object(agent.memory_router, "_invoke_manifest", side_effect=invoke_manifest),
        mock.patch(
            "core.agent_runtime.builder.app_builder.build_app_from_spec",
            side_effect=build_app_from_spec,
        ),
        mock.patch(
            "core.agent_runtime.builder.app_builder.render_app_build_response",
            return_value="Built it.",
        ),
        # The LOCAL lane. Any call to it on a pinned turn is the exact bug this file exists for.
        mock.patch.object(
            agent_builder_controller,
            "build_ollama_generate_fn",
            side_effect=AssertionError("the local Ollama lane generated a PINNED build"),
        ),
    ):
        return agent_builder_controller._run_model_build(
            agent,
            task=task,
            effective_input="i need median.py with a median function",
            classification={"task_class": "system_design"},
            interpretation=None,
            session_id="pinned-build-test",
            source_context=ctx,
            target={"root_dir": "v5", "platform": "generic", "language": "python"},
            load_active_persona_fn=lambda *a, **k: None,
        )


