def _line(kind: str, uuid: str | None, parent: str | None, content=None, *, role: str | None = None, **extra) -> dict:
    record = {"type": kind, "sessionId": "sess-harbor", "cwd": "/old/harbor", "gitBranch": "tide-check",
              "timestamp": "2026-09-01T10:00:00.000Z", **extra}
    if uuid is not None:
        record["uuid"] = uuid
        record["parentUuid"] = parent
    if content is not None:
        record["message"] = {"role": role or kind, "content": content}
    return record


