"""A terminal coding assistant's per-project transcripts and settings (synthetic, documented layout).

Each store is built from the tool's published locations and its vendor's own transcript parser:
``projects/<folder-with-dashes>/<session>.jsonl`` lines that chain through ``uuid``/``parentUuid``.
The tests pin the conversation a person saw (newest main branch, no helper or injected turns),
what is carried as reviewed context (summary, to-do list, folder, branch, models), how the
tool's own instruction order, imports, rules, memory, drafts and tool servers are reviewed, and
that damaged, locked, linked and oversized stores fail plainly with nothing changed or leaked.
"""
