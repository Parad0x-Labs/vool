def test_review_follows_the_tools_order_imports_rules_memory_and_servers_without_secrets(tmp_path):
    home = tmp_path / "home"
    _tool_settings(home)
    _write(home, "sess-harbor", _conversation())
    project = _project(tmp_path)
    [chat] = _read(home).chats
    before = _fingerprint(home)
    plan = review(chat, root=str(project), old_root="/old/harbor")
    text = json.dumps(plan)
    assert SECRET not in text and "oauthAccount" not in text
    instructions = " ".join(row["text"] for row in plan["instructions"])
    for marker in ("compass_marker", "style_marker", "import_marker", "second_marker", "local_marker", "rule_marker"):
        assert marker in instructions, marker
    assert "@not/imported.md" in instructions and "escape_marker" not in text and "agents_marker" not in text
    assert "conditional_marker" not in instructions
    drafts = " ".join(skill["body"] for skill in plan["skills"])
    for marker in ("reviewer_marker", "ship_marker", "tides_marker", "tester_marker", "conditional_marker"):
        assert marker in drafts, marker
    assert "conditional_rules_staged" in plan["notices"]
    memories = " ".join(row["text"] for row in plan["memories"])
    assert "amber_marker" in memories and "labels.md" in memories
    assert {"model-new", "model-project"} <= set(plan["models"])
    assert {(tool["name"], tool["command"]) for tool in plan["tools"]} == {
        ("ledger", "python3"), ("tide", "node"), ("shared", "uvx")}
    assert "tool_transport_unsupported" in plan["warnings"] and "other-tool" not in text
    assert {Path(row["path"]).name: row["status"] for row in plan["files"] if row["path"]}.get("ledger.md") == "exists"
    assert _fingerprint(home) == before
    (project / "CLAUDE.md").unlink()
    (project / ".claude" / "CLAUDE.md").unlink()
    (project / "CLAUDE.local.md").unlink()
    plan = review(chat, root=str(project))
    assert "agents_marker" in " ".join(row["text"] for row in plan["instructions"])


