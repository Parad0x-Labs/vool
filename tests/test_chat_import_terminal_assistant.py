def test_import_through_the_doors_with_disabled_tools_and_gated_summary(served, tmp_path):
    from core.execution.mcp_bridge import load_mcp_server_configs
    from core.prompt_normalizer import _reviewed_working_context_messages
    from core.runtime_paths import active_vool_home

    home = Path(os.environ["HOME"])
    _tool_settings(home)
    _write(home, "sess-harbor", _models(_conversation()))
    project = _project(tmp_path)
    before = _fingerprint(home)
    status, sources = _call(served, "GET", "/api/chat/import/sources")
    assert status == 200 and [s["kind"] for s in sources["local"]] == ["terminal_assistant"]
    sessions = {}
    for continuation in (False, True):
        status, preview = _call(served, "POST", "/api/chat/import/preview", body={"source": "local_terminal_assistant"})
        assert status == 200, preview
        assert [c["title"] for c in preview["chats"]] == ["Harbor release"]
        status, reviewed = _call(served, "POST", "/api/chat/import/context", body={
            "preview_id": preview["preview_id"], "ref": "0", "root": str(project), "old_root": "/old/harbor"})
        assert status == 200, reviewed
        assert SECRET not in json.dumps(reviewed)
        run = _finish(served, preview, continuation=continuation, contexts={"0": {
            "plan_id": reviewed["plan_id"], "options": {"instructions": True, "tools": True, "skills": True, "memories": True}}})
        sessions[continuation] = run["first_session_id"]
        evidence = _reviewed_working_context_messages({"runtime_session_id": run["first_session_id"]})[0].content
        assert ("ledger next" in evidence) is continuation and ("release ledger" in evidence) is continuation
        if not continuation:
            assert store.continuation_history(run["first_session_id"]) == []
            status, result = _call(served, "POST", "/api/chat/import/undo", body={"batch_id": run["run_id"]})
            assert status == 200, result
    history = store.continuation_history(sessions[True])
    assert [row["content"] for row in history] == [
        "Plan the harbor release.", "Checking the tide first.", "Now write the ledger.", "The ledger is written."]
    assert load_mcp_server_configs() == []
    for path in active_vool_home().rglob("*"):
        if path.is_file():
            assert SECRET.encode() not in path.read_bytes(), path
    assert _fingerprint(home) == before
